// Regenerates the Material Icon Theme lookup table and the icons it points at.
// Run after bumping the material-icon-theme dependency:
//   node scripts/sync-file-icons.mjs
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { generateManifest } = require("material-icon-theme");
const { version } = require("material-icon-theme/package.json");
const packageRoot = dirname(require.resolve("material-icon-theme/package.json"));

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const iconDirectory = join(webRoot, "public", "file-icons");
const mapFile = join(webRoot, "src", "shared", "file-icon-map.ts");

const manifest = generateManifest({});

// Theme keys arrive in mixed case; the lookup lowercases before matching, so
// fold them here and let the first spelling win.
function lowercased(entries) {
  const table = {};
  for (const [key, icon] of Object.entries(entries)) table[key.toLowerCase()] ??= icon;
  return table;
}

const extensions = lowercased(manifest.fileExtensions);
const names = lowercased(manifest.fileNames);
const used = [...new Set([...Object.values(extensions), ...Object.values(names), manifest.file])].sort();

await rm(iconDirectory, { recursive: true, force: true });
await mkdir(iconDirectory, { recursive: true });

const missing = [];
for (const icon of used) {
  // Around 70 icons are clones and do not live at icons/<id>.svg, so always
  // take the path the manifest gives. It is relative to the manifest in dist/.
  const iconPath = manifest.iconDefinitions[icon]?.iconPath;
  if (!iconPath) {
    missing.push(icon);
    continue;
  }
  await cp(resolve(packageRoot, "dist", iconPath), join(iconDirectory, `${icon}.svg`));
}
if (missing.length) throw new Error(`No icon definition for: ${missing.join(", ")}`);

function literal(table) {
  return Object.entries(table)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, icon]) => `  ${JSON.stringify(key)}: ${JSON.stringify(icon)},`)
    .join("\n");
}

await writeFile(
  mapFile,
  `// Generated by scripts/sync-file-icons.mjs from material-icon-theme@${version}. Do not edit.
// The Record annotations are deliberate: without them TypeScript infers a
// literal type with one member per key, which is slow and pointless here.

export const defaultFileIcon = ${JSON.stringify(manifest.file)};

export const fileIconNames: Record<string, string> = {
${literal(names)}
};

export const fileIconExtensions: Record<string, string> = {
${literal(extensions)}
};
`,
);

console.log(
  `${used.length} icons -> public/file-icons, ${Object.keys(names).length + Object.keys(extensions).length} lookup keys`,
);
